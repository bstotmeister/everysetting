-- Core.lua: profiles and sharing them, undo and redo, and resetting to the game's defaults.

local T = ...
local W = dofile("tests/wow.lua")

-- `saved` and `savedChar` are the account's and the character's saved variables.
local function Start(saved, before, savedChar)
	local EverySetting = W.Load(saved, savedChar)
	W.AddCVar("farclip", "1000")
	W.AddCVar("RAIDfarclip", "1000")
	W.AddCVar("shadowSoft", "0")
	W.AddCVar("ffxGlow", "1")
	W.AddCVar("nameplateMotionSpeed", "0.025000", { secure = true })
	W.AddCVar("physicsLevel", "1")
	W.AddCVar("someRawCVar", "5")
	W.AddCVar("gxMonitor", "0", { readOnly = true })
	EverySetting.GROUPS = { { title = "Knobs", items = {
		{ cvar = "farclip", label = "View distance", type = "slider", min = 1000, max = 10000, step = 100, raid = "RAIDfarclip" },
		{ cvar = "shadowSoft", label = "Soft shadows", type = "toggle" },
		{ cvar = "ffxGlow", label = "Glow", type = "toggle" },
		{ cvar = "nameplateMotionSpeed", label = "Nameplate speed", type = "slider", min = 0, max = 1, step = 0.005 },
		{ cvar = "physicsLevel", label = "Physics", type = "slider", min = 0, max = 2, step = 1, restart = "client" },
	} } }
	EverySetting.SECTIONS = { "Everything" }
	EverySetting.CVARS = {}
	if before then before() end
	W.Login()
	return EverySetting
end

-- The top preset's values, as the game would have them before Every Setting.
local function Preset()
	C_CVar.SetCVar("farclip", "10000")
	C_CVar.SetCVar("RAIDfarclip", "6000")
end

T.test("profiles: values kept before there were profiles become Default", function()
	local EverySetting = Start({ values = { shadowSoft = "1" }, before = { shadowSoft = "0" } })
	T.eq(EverySetting.GetProfile(), "Default")
	T.eq(EverySettingDB.values, nil)
	T.eq(EverySettingDB.profiles.Default.shadowSoft, "1")
	T.eq(C_CVar.GetCVar("shadowSoft"), "1", "and are still set at login")
	T.eq(table.concat(EverySetting.GetProfiles(), ","), "Default")
end)

T.test("profiles: Save as copies the profile in use and switches to it", function()
	local EverySetting = Start()
	EverySetting.Set("shadowSoft", true)
	T.eq(EverySetting.NewProfile("  Raid night "), nil, "saved")
	T.eq(EverySetting.GetProfile(), "Raid night", "trimmed, and in use")
	T.eq(EverySettingCharDB.profile, "Raid night", "this character's from now on")
	T.eq(EverySettingDB.applied, "Raid night")
	T.ok(EverySetting.IsStored("shadowSoft"), "the copy keeps the same values")
	EverySetting.Set("farclip", 5000)
	T.eq(EverySettingDB.profiles.Default.farclip, nil, "changes go into the profile in use only")
	T.eq(EverySettingDB.profiles["Raid night"].farclip, "5000")
	T.ok(EverySetting.NewProfile(""), "a name is needed")
	T.ok(EverySetting.NewProfile("raid NIGHT"), "names differ by more than case")
	T.ok(EverySetting.NewProfile(("x"):rep(33)), "and aren't too long")
	EverySetting.NewProfile("alpha")
	T.eq(table.concat(EverySetting.GetProfiles(), ","), "Default,alpha,Raid night", "Default first, then by name")
end)

T.test("profiles: switching sets the new profile's values and puts back the rest", function()
	local EverySetting = Start(nil, Preset)
	EverySetting.Set("shadowSoft", true) -- kept by both
	EverySetting.NewProfile("Pretty")
	EverySetting.Set("farclip", 9000)
	EverySetting.Set("ffxGlow", false)
	T.eq(EverySetting.SetProfile("default"), "Default", "found whatever its case")
	T.eq(C_CVar.GetCVar("farclip"), "10000", "only Pretty keeps it: back to the preset's value")
	T.eq(C_CVar.GetCVar("RAIDfarclip"), "6000", "and its raid twin")
	T.eq(C_CVar.GetCVar("ffxGlow"), "1")
	T.eq(C_CVar.GetCVar("shadowSoft"), "1", "both keep it")
	T.ok(not EverySetting.IsStored("farclip") and EverySetting.IsStored("shadowSoft"))
	EverySetting.Set("shadowSoft", false) -- Default now keeps it off
	EverySetting.SetProfile("Pretty")
	T.eq(C_CVar.GetCVar("farclip"), "9000")
	T.eq(C_CVar.GetCVar("RAIDfarclip"), "9000")
	T.eq(C_CVar.GetCVar("ffxGlow"), "0")
	T.eq(C_CVar.GetCVar("shadowSoft"), "1", "Pretty's own value")
	EverySetting.Reset("farclip")
	T.eq(C_CVar.GetCVar("farclip"), "10000", "Reset still knows the value from before Every Setting")
	T.eq(C_CVar.GetCVar("RAIDfarclip"), "6000")
	local name, why = EverySetting.SetProfile("nope")
	T.ok(name == nil and why, "no such profile")
end)

T.test("profiles: each character's own profile is put in use when it logs in", function()
	-- The last character played was on Default; this one uses Pretty.
	local saved = {
		applied = "Default",
		profiles = { Default = { shadowSoft = "1" }, Pretty = { farclip = "9000", someRawCVar = "8" } },
		before = { shadowSoft = "0" },
	}
	local EverySetting = Start(saved, function() C_CVar.SetCVar("shadowSoft", "1") end, { profile = "Pretty" })
	T.eq(EverySetting.GetProfile(), "Pretty")
	T.eq(EverySettingDB.applied, "Pretty")
	T.eq(C_CVar.GetCVar("farclip"), "9000")
	T.eq(C_CVar.GetCVar("someRawCVar"), "8", "a CVar that isn't in Knobs.lua too")
	T.eq(C_CVar.GetCVar("shadowSoft"), "0", "what only the other character's profile keeps is put back")
	-- A new character starts on Default.
	EverySetting = Start({ applied = "Pretty", profiles = { Default = {}, Pretty = { farclip = "9000" } }, before = { farclip = "1000" } },
		function() C_CVar.SetCVar("farclip", "9000") end)
	T.eq(EverySetting.GetProfile(), "Default")
	T.eq(C_CVar.GetCVar("farclip"), "1000")
end)

T.test("profiles: a character whose profile was deleted elsewhere falls back to Default", function()
	local EverySetting = Start({ applied = "Default", profiles = { Default = { shadowSoft = "1" } } }, nil, { profile = "Gone" })
	T.eq(EverySetting.GetProfile(), "Default")
	T.eq(C_CVar.GetCVar("shadowSoft"), "1")
	T.ok(W.chat[1]:find("the profile Gone was deleted", 1, true), W.chat[1])
end)

T.test("profiles: a login in combat switches profile when combat ends", function()
	local saved = { applied = "Default", profiles = { Default = {}, Pretty = { farclip = "9000", nameplateMotionSpeed = "0.5" } } }
	local EverySetting = Start(saved, function() W.combat = true end, { profile = "Pretty" })
	T.eq(C_CVar.GetCVar("farclip"), "1000", "not yet")
	W.Combat(false)
	T.eq(C_CVar.GetCVar("farclip"), "9000")
	T.eq(C_CVar.GetCVar("nameplateMotionSpeed"), "0.5")
	T.eq(EverySettingDB.applied, "Pretty")
	T.ok(EverySetting.IsStored("farclip"))
end)

T.test("sharing: a profile exports as a line of text, and imports as a new profile", function()
	local EverySetting = Start()
	EverySetting.RawKnob("someRawCVar", "")
	EverySetting.Set("farclip", 9000)
	EverySetting.Set("shadowSoft", true)
	EverySetting.Set("someRawCVar", "a b,c=d", true)
	local text = EverySetting.ExportProfile()
	T.eq(text, "EverySetting:1:farclip=9000,shadowSoft=1,someRawCVar=a%20b%2Cc%3Dd", "in name order, escaped")
	EverySetting.ResetAll()
	T.eq(EverySetting.ImportProfile("Shared", "  " .. text .. "\n"), nil, "imported")
	T.eq(EverySetting.GetProfile(), "Shared")
	T.eq(C_CVar.GetCVar("farclip"), "9000")
	T.eq(C_CVar.GetCVar("RAIDfarclip"), "9000")
	T.eq(C_CVar.GetCVar("someRawCVar"), "a b,c=d")
	T.eq(EverySetting.ExportProfile(), text, "and exports the same")
	T.eq(EverySettingDB.profiles.Default.farclip, nil, "the profile it was imported over is untouched")
end)

T.test("sharing: an import takes only what this client can be given", function()
	local EverySetting = Start()
	local text = "EverySetting:1:farclip=99999,FARCLIP=5000,shadowSoft=7,notInThisClient=1,gxMonitor=2,ffxGlow=abc,physicsLevel=2"
	T.eq(EverySetting.ImportProfile("Odd", text), nil)
	local kept = EverySettingDB.profiles.Odd
	T.eq(kept.farclip, "10000", "a knob's value is held to its range, and the first one wins")
	T.eq(kept.shadowSoft, "0", "a toggle is 0 or 1")
	T.eq(kept.ffxGlow, "0")
	T.eq(kept.physicsLevel, "2")
	T.eq(kept.notInThisClient, nil, "a CVar the client doesn't have is skipped")
	T.eq(kept.gxMonitor, nil, "and one it locks")
	T.eq(C_CVar.GetCVar("physicsLevel"), "2")
end)

T.test("sharing: bad names and strings are turned down, with a reason", function()
	local EverySetting = Start()
	local good = "EverySetting:1:shadowSoft=1"
	T.ok(EverySetting.ImportProfile("", good):find("name", 1, true))
	T.ok(EverySetting.ImportProfile("default", good):find("already", 1, true))
	T.ok(EverySetting.ImportProfile("New", "FadeUI:1:fadeIn=2"):find("isn't an Every Setting profile", 1, true))
	T.ok(EverySetting.ImportProfile("New", "EverySetting:9:shadowSoft=1"):find("newer version", 1, true))
	T.ok(EverySetting.ImportProfile("New", "EverySetting:1:"):find("empty or damaged", 1, true))
	T.ok(EverySetting.ImportProfile("New", "EverySetting:1:notInThisClient=1"):find("empty or damaged", 1, true))
	T.ok(EverySetting.ImportProfile("New", nil))
	W.Combat(true)
	T.ok(EverySetting.ImportProfile("New", good):find("combat", 1, true))
	W.Combat(false)
	T.eq(#EverySetting.GetProfiles(), 1, "nothing was made")
	T.eq(EverySetting.GetProfile(), "Default")
end)

T.test("profiles: deleting switches to Default, which can't be deleted", function()
	local EverySetting = Start()
	T.ok(EverySetting.DeleteProfile(), "not Default")
	EverySetting.NewProfile("Pretty")
	EverySetting.Set("farclip", 9000)
	T.eq(EverySetting.DeleteProfile(), nil)
	T.eq(EverySetting.GetProfile(), "Default")
	T.eq(EverySettingDB.profiles.Pretty, nil)
	T.eq(C_CVar.GetCVar("farclip"), "1000", "what it kept is put back")
end)

T.test("profiles: copying from a profile replaces what this one keeps", function()
	local EverySetting = Start()
	EverySetting.Set("shadowSoft", true)
	EverySetting.NewProfile("Pretty")
	EverySetting.Reset("shadowSoft")
	EverySetting.Set("farclip", 9000)
	EverySetting.SetProfile("Default")
	EverySetting.CopyProfile("Pretty")
	T.eq(EverySetting.GetProfile(), "Default", "still on this profile")
	T.eq(C_CVar.GetCVar("farclip"), "9000")
	T.eq(C_CVar.GetCVar("shadowSoft"), "0", "what Pretty doesn't keep is reset")
	T.ok(EverySetting.IsStored("farclip") and not EverySetting.IsStored("shadowSoft"))
	T.ok(EverySetting.Undo(), "and it can be undone")
	T.eq(C_CVar.GetCVar("farclip"), "1000")
	T.eq(C_CVar.GetCVar("shadowSoft"), "1")
end)

T.test("profiles: they can't be switched or deleted in combat", function()
	local EverySetting = Start()
	EverySetting.NewProfile("Pretty")
	W.Combat(true)
	local name, why = EverySetting.SetProfile("Default")
	T.ok(name == nil and why:find("combat"))
	T.ok(EverySetting.DeleteProfile():find("combat"))
	T.eq(EverySetting.GetProfile(), "Pretty")
end)

T.test("undo: a change can be taken back and made again", function()
	local EverySetting = Start(nil, Preset)
	T.eq(select("#", EverySetting.HistorySize()), 2)
	T.ok(not EverySetting.Undo(), "nothing to undo yet")
	EverySetting.Set("farclip", 8000)
	EverySetting.Set("farclip", 5000)
	EverySetting.Set("shadowSoft", true)
	local undo, redo = EverySetting.HistorySize()
	T.eq(undo, 3) T.eq(redo, 0)
	T.ok(EverySetting.Undo())
	T.eq(C_CVar.GetCVar("shadowSoft"), "0")
	T.ok(not EverySetting.IsStored("shadowSoft"), "not kept any more")
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "8000")
	T.eq(C_CVar.GetCVar("RAIDfarclip"), "8000", "the raid twin goes with it")
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "10000", "back to the preset's value")
	T.eq(C_CVar.GetCVar("RAIDfarclip"), "6000")
	T.eq(next(EverySettingDB.before), nil, "as if Every Setting had never touched it")
	T.ok(not EverySetting.Undo())
	T.ok(EverySetting.Redo())
	T.eq(C_CVar.GetCVar("farclip"), "8000")
	T.eq(EverySetting.Before("farclip"), "10000")
	EverySetting.Redo()
	T.eq(C_CVar.GetCVar("farclip"), "5000")
	-- A new change clears what could be redone.
	EverySetting.Undo()
	EverySetting.Set("farclip", 2000)
	local _, left = EverySetting.HistorySize()
	T.eq(left, 0)
	T.ok(not EverySetting.Redo())
end)

T.test("undo: setting a knob to the value it has isn't a step, but keeping it is", function()
	local EverySetting = Start()
	EverySetting.Set("farclip", 1000) -- its value already, but now kept
	T.eq((EverySetting.HistorySize()), 1)
	EverySetting.Set("farclip", 1000)
	T.eq((EverySetting.HistorySize()), 1, "nothing changed")
	EverySetting.Undo()
	T.ok(not EverySetting.IsStored("farclip"))
end)

T.test("undo: a reset is one step, however many knobs it covers", function()
	local EverySetting = Start()
	EverySetting.Set("farclip", 8000)
	EverySetting.Set("shadowSoft", true)
	EverySetting.Set("physicsLevel", 2)
	EverySetting.restart.client = nil
	T.eq(EverySetting.ResetAll(), 3)
	T.eq(C_CVar.GetCVar("farclip"), "1000")
	T.eq((EverySetting.HistorySize()), 4)
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "8000")
	T.eq(C_CVar.GetCVar("shadowSoft"), "1")
	T.ok(EverySetting.IsStored("farclip") and EverySetting.IsStored("shadowSoft"))
	T.eq(EverySetting.restart.client, true, "a knob that needs a restart still says so")
	W.Slash("undo")
	T.eq(C_CVar.GetCVar("physicsLevel"), "1")
	W.Slash("redo")
	T.eq(C_CVar.GetCVar("physicsLevel"), "2")
end)

T.test("undo: not in combat, and a change made in combat can't be taken back", function()
	local EverySetting = Start()
	EverySetting.Set("farclip", 8000)
	W.Combat(true)
	T.ok(not EverySetting.Undo(), "not in combat")
	T.eq(C_CVar.GetCVar("farclip"), "8000")
	T.eq((EverySetting.HistorySize()), 1, "still there for later")
	EverySetting.Set("nameplateMotionSpeed", 0.5) -- waits for combat to end
	T.eq((EverySetting.HistorySize()), 0, "history can't span a change that's still waiting")
	W.Combat(false)
	T.eq(C_CVar.GetCVar("nameplateMotionSpeed"), "0.5")
	T.ok(not EverySetting.Undo())
end)

T.test("undo: each profile remembers its own changes", function()
	local EverySetting = Start()
	EverySetting.Set("farclip", 8000)
	EverySetting.NewProfile("Pretty")
	T.eq((EverySetting.HistorySize()), 0, "a new profile starts with none")
	EverySetting.Set("farclip", 9000)
	EverySetting.Set("shadowSoft", true)
	EverySetting.SetProfile("Default")
	T.eq((EverySetting.HistorySize()), 1, "Default's are still there")
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "1000")
	T.ok(not EverySetting.IsStored("farclip"))
	EverySetting.SetProfile("Pretty")
	T.eq((EverySetting.HistorySize()), 2)
	EverySetting.Undo()
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "8000", "back to how Pretty started")
	T.eq(C_CVar.GetCVar("shadowSoft"), "0")
end)

T.test("undo: only the last 50 changes are remembered", function()
	local EverySetting = Start()
	for i = 1, 60 do EverySetting.Set("farclip", 1000 + i * 100) end
	T.eq((EverySetting.HistorySize()), 50)
end)

T.test("defaults: a knob can go to the game's default instead of how it was", function()
	local EverySetting = Start(nil, Preset)
	EverySetting.Set("farclip", 8000)
	EverySetting.Reset("farclip", true)
	T.eq(C_CVar.GetCVar("farclip"), "1000", "the game's default, not the preset's 10000")
	T.eq(C_CVar.GetCVar("RAIDfarclip"), "1000", "the raid twin's default")
	T.ok(not EverySetting.IsStored("farclip"), "and it isn't kept")
	T.eq(next(EverySettingDB.before), nil)
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "8000")
	T.eq(EverySetting.Before("farclip"), "10000", "Reset would still go back to the preset's value")
	-- A knob Every Setting doesn't keep can go to its default too; a plain Reset leaves it alone.
	EverySetting.Reset("farclip")
	EverySetting.Reset("farclip")
	T.eq(C_CVar.GetCVar("farclip"), "10000")
	EverySetting.Reset("farclip", true)
	T.eq(C_CVar.GetCVar("farclip"), "1000")
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "10000")
end)

T.test("defaults: Reset all can go to the game's defaults", function()
	local EverySetting = Start(nil, Preset)
	EverySetting.Set("farclip", 8000)
	EverySetting.Set("ffxGlow", false)
	T.eq(EverySetting.ResetAll(true), 2)
	T.eq(C_CVar.GetCVar("farclip"), "1000")
	T.eq(C_CVar.GetCVar("ffxGlow"), "1")
	T.eq(next(EverySettingDB.profiles.Default), nil)
	EverySetting.Undo()
	T.eq(C_CVar.GetCVar("farclip"), "8000")
	T.eq(C_CVar.GetCVar("ffxGlow"), "0")
end)

